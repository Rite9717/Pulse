import { NODE_CATEGORY_META } from './simulator.js';

function sanitizeId(id) {
  return String(id || 'service')
    .toLowerCase()
    .replace(/[^a-z0-9-_]/g, '-');
}

export function generateDockerComposeSpec(topology, simulation) {
  const lines = [
    `# Generated by Pulse Studio — Architecture & Chaos Workbench`,
    `# Topology: ${topology.name}`,
    `# Target Ingress: ${simulation.ingressRps} RPS | E2E p95: ${simulation.e2eP95Ms}ms | Est. Cost: $${simulation.totalCostPerHour}/hr`,
    `services:`,
  ];

  const outgoing = new Map();
  for (const e of topology.edges || []) {
    if (!outgoing.has(e.from)) outgoing.set(e.from, []);
    outgoing.get(e.from).push(e.to);
  }

  for (const node of topology.nodes || []) {
    const svcName = sanitizeId(node.id);
    const meta = NODE_CATEGORY_META[node.category] || NODE_CATEGORY_META.worker;
    const m = simulation.nodeMetrics[node.id] || {};
    const deps = outgoing.get(node.id) || [];

    lines.push(`  ${svcName}:`);
    lines.push(`    image: ${node.image || meta.image}`);
    lines.push(`    deploy:`);
    lines.push(`      replicas: ${node.replicas || 1}`);
    lines.push(`      resources:`);
    lines.push(`        limits:`);
    lines.push(
      `          cpus: "${node.category === 'llm' ? '8.0' : node.category === 'vector' ? '4.0' : '2.0'}"`
    );
    lines.push(
      `          memory: ${node.category === 'llm' ? '32G' : node.category === 'vector' ? '8G' : '2G'}`
    );
    lines.push(`    environment:`);
    lines.push(`      - SERVICE_NAME=${svcName}`);
    lines.push(`      - MAX_CONCURRENCY=${node.concurrencyPerReplica || 16}`);
    lines.push(`      - QUEUE_DEPTH=${node.queueDepth || 256}`);
    lines.push(`      - RETRY_BUDGET=${node.retries ?? 1}`);
    lines.push(`      - EXPECTED_ARRIVAL_RPS=${m.arrivalRps ?? 0}`);
    if (node.category === 'cache') {
      lines.push(`      - SEMANTIC_CACHE_HIT_TARGET=${node.cacheHitRate ?? 0.4}`);
    }
    if (node.category === 'llm') {
      lines.push(`      - MAX_PROMPT_TOKENS=${node.promptTokens ?? 1024}`);
      lines.push(`      - MAX_COMPLETION_TOKENS=${node.completionTokens ?? 256}`);
    }
    if (deps.length > 0) {
      lines.push(`    depends_on:`);
      for (const d of deps) {
        lines.push(`      - ${sanitizeId(d)}`);
      }
    }
    lines.push('');
  }

  return lines.join('\n');
}

export function generateKubernetesHpaSpec(topology, simulation) {
  const blocks = [];

  for (const node of topology.nodes || []) {
    const svcName = sanitizeId(node.id);
    const meta = NODE_CATEGORY_META[node.category] || NODE_CATEGORY_META.worker;
    const m = simulation.nodeMetrics[node.id] || {};
    const minReplicas = Math.max(1, node.replicas || 2);
    const maxReplicas = Math.max(minReplicas * 3, Math.ceil((m.arrivalRps || 50) / 20));

    blocks.push(`apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${svcName}
  labels:
    app: ${svcName}
    tier: ${node.category}
spec:
  replicas: ${minReplicas}
  selector:
    matchLabels:
      app: ${svcName}
  template:
    metadata:
      labels:
        app: ${svcName}
    spec:
      containers:
        - name: ${svcName}
          image: ${node.image || meta.image}
          ports:
            - containerPort: ${meta.defaultPort}
          env:
            - name: MAX_CONCURRENCY_PER_POD
              value: "${node.concurrencyPerReplica || 16}"
            - name: CIRCUIT_BREAKER_QUEUE_DEPTH
              value: "${node.queueDepth || 256}"
---
apiVersion: autoscaling/v2
kind: HorizontalPodAutoscaler
metadata:
  name: ${svcName}-hpa
spec:
  scaleTargetRef:
    apiVersion: apps/v1
    kind: Deployment
    name: ${svcName}
  minReplicas: ${minReplicas}
  maxReplicas: ${maxReplicas}
  metrics:
    - type: Resource
      resource:
        name: cpu
        target:
          type: Utilization
          averageUtilization: 75`);
  }

  return blocks.join('\n---\n');
}

export function generateArchitectureRFC(topology, simulation, chaosState, diagnostics) {
  const rows = (topology.nodes || []).map((n) => {
    const m = simulation.nodeMetrics[n.id] || {};
    return `| **${n.name}** (\`${n.category}\`) | ${m.effectiveReplicas}/${n.replicas} | ${m.arrivalRps} RPS | ${Math.round((m.utilization || 0) * 100)}% | ${m.p50Ms}ms / **${m.p95Ms}ms** / ${m.p99Ms}ms | ${(m.errorRate * 100).toFixed(2)}% | $${(m.totalCostPerHour || 0).toFixed(2)}/hr |`;
  });

  const diagLines = (diagnostics || []).map(
    (d) => `- **[${d.severity.toUpperCase()}] ${d.title}**: ${d.detail} *Recommendation:* ${d.recommendation}`
  );

  return `# Architecture & Chaos Resilience RFC: ${topology.name}

> Generated by **Pulse Studio** · Target Load: **${simulation.ingressRps} RPS** · Chaos Profile: **${chaosState.mode || 'none'}**

## 1. Executive Summary & SLO Posture

| Metric | Measured Value | Target / Budget | Status |
| :--- | :--- | :--- | :--- |
| **End-to-End Latency (p50 / p95 / p99)** | ${simulation.e2eP50Ms}ms / **${simulation.e2eP95Ms}ms** / ${simulation.e2eP99Ms}ms | <= ${simulation.sloLatencyTargetMs}ms (p95) | ${simulation.sloMet ? 'PASS' : 'BREACH'} |
| **Effective Throughput** | **${simulation.effectiveThroughputRps} RPS** | ${simulation.ingressRps} RPS Ingress | ${simulation.availabilityPct}% Avail |
| **Resilience Score** | **${simulation.resilienceScore} / 100** | >= 80 / 100 | ${simulation.resilienceScore >= 80 ? 'HEALTHY' : 'AT RISK'} |
| **Hourly Burn / Monthly Run-Rate** | **$${simulation.totalCostPerHour.toFixed(2)}/hr** ($${simulation.monthlyProjectedCost.toLocaleString()}/mo) | $${simulation.costPer1kRequests}/1k req | ${simulation.totalTokensPerSec.toLocaleString()} tok/s |
| **Primary Bottleneck** | \`${simulation.bottleneckNodeName}\` | Peak Util: ${Math.round(simulation.maxUtilization * 100)}% | Critical Path: \`${simulation.criticalPathNodeIds.join(' -> ')}\` |

## 2. Per-Service Queueing & Economics Breakdown

| Service Node | Replicas | Arrival Load | Queue Util | Latency (p50 / p95 / p99) | Drop / Error | Est. Cost |
| :--- | :---: | :---: | :---: | :---: | :---: | :---: |
${rows.join('\n')}

## 3. Automated SRE & Capacity Diagnostics

${diagLines.join('\n')}
`;
}
